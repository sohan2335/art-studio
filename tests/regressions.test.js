import {test} from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import {once} from 'node:events';
import {mkdtempSync,rmSync,readFileSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createStudio} from '../server.js';

test('Request handling, exact passwords, sessions, static assets and restart persistence',async t=>{
 const dir=mkdtempSync(join(tmpdir(),'studio-final-'));const dbPath=join(dir,'test.sqlite');
 let app=createStudio({dbPath,studioPassword:'Temporary test password'});
 const start=async()=>{app.server.listen(0,'127.0.0.1');await once(app.server,'listening');return `http://127.0.0.1:${app.server.address().port}`;};
 const stop=async()=>{await new Promise(r=>app.server.close(r));app.db.close();};
 let base=await start();t.after(async()=>{await stop();rmSync(dir,{recursive:true,force:true});});
 const request=(path,body,cookie='')=>fetch(base+path,{method:body?'POST':'GET',headers:{'Content-Type':'application/json',Cookie:cookie},body:body?JSON.stringify(body):undefined});
 const password='  exact password  ';
 let r=await request('/api/register',{name:'Space User',email:'spaces@example.test',password});assert.equal(r.status,200);
 const cookie=r.headers.get('set-cookie').split(';')[0];assert.match(r.headers.get('set-cookie'),/HttpOnly/);assert.match(r.headers.get('set-cookie'),/SameSite=Strict/);
 assert.equal((await request('/api/login',{email:'spaces@example.test',password:password.trim()})).status,401);
 assert.equal((await request('/api/login',{email:'spaces@example.test',password})).status,200);
 assert.equal((await request('/api/me',undefined,'other=value;'+cookie)).status,200);
 const bytes=Buffer.from(JSON.stringify({name:'कला Studio',email:'unicode@example.test',password:'Unicode pass'}));
 const cut=bytes.indexOf(Buffer.from('क'))+1;
 const unicode=await new Promise((resolve,reject)=>{const q=http.request(base+'/api/register',{method:'POST',headers:{'Content-Type':'application/json'}},res=>{let data='';res.on('data',c=>data+=c);res.on('end',()=>resolve({status:res.statusCode,data:JSON.parse(data)}));});q.on('error',reject);q.write(bytes.subarray(0,cut));setTimeout(()=>q.end(bytes.subarray(cut)),20);});
 assert.equal(unicode.status,200);assert.equal(unicode.data.user.name,'कला Studio');
 r=await fetch(base+'/api/login',{method:'POST',headers:{'Content-Type':'application/json-invalid'},body:'{}'});assert.equal(r.status,415);
 r=await fetch(base+'/api/login',{method:'POST',headers:{'Content-Type':'application/json'},body:' '.repeat(25000)});assert.equal(r.status,413);
 assert.equal((await fetch(base+'/%broken')).status,400);
 assert.equal((await fetch(base+'/missing-page')).status,404);
 for(const page of ['/','/collection.html','/wall-art.html','/pottery.html','/profile.html','/app.js','/styles.css'])assert.equal((await fetch(base+page)).status,200,page);
 const seed=JSON.parse(readFileSync(new URL('../data/seed.json',import.meta.url)));
 for(const p of seed.paintings)assert.ok(existsSync(new URL('../public/'+p.imageUrl,import.meta.url)),p.imageUrl);
 const order=await request('/api/orders',{painting_id:'p-001',price:1},cookie);assert.equal(order.status,200);
 const id=(await order.json()).id;await stop();app=createStudio({dbPath});base=await start();
 assert.equal(app.initialStudioPassword,undefined);assert.equal(app.db.prepare('SELECT count(*) n FROM paintings').get().n,12);
 r=await request('/api/orders/'+id,undefined,cookie);assert.equal(r.status,200);assert.equal((await r.json()).record.price,seed.paintings[0].price);
 app.db.prepare('UPDATE sessions SET expires=0').run();assert.equal((await request('/api/me',undefined,cookie)).status,401);
});
